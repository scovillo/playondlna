const supportedLanguages = Object.keys(translations);
const screenshotDirectories = {
  en: "assets/screenshots",
  de: "assets/screenshots/de",
};

function preferredLanguage() {
  const queryLanguage = new URLSearchParams(window.location.search).get("lang");
  if (supportedLanguages.includes(queryLanguage)) return queryLanguage;

  const savedLanguage = window.localStorage.getItem("playondlna-language");
  if (supportedLanguages.includes(savedLanguage)) return savedLanguage;

  const browserLanguage = navigator.language.toLowerCase().split("-")[0];
  return supportedLanguages.includes(browserLanguage) ? browserLanguage : "en";
}

function updateMeta(name, content, property = false) {
  const attribute = property ? "property" : "name";
  const element = document.querySelector(`meta[${attribute}="${name}"]`);
  if (element) element.setAttribute("content", content);
}

function updateScreenshots(language) {
  const englishDirectory = screenshotDirectories.en;
  const localizedDirectory = screenshotDirectories[language] ?? englishDirectory;

  document.querySelectorAll("[data-screenshot]").forEach((image) => {
    const fileName = `Screenshot_PlayOnDlna_${image.dataset.screenshot}.png`;
    const fallbackSource = `${englishDirectory}/${fileName}`;
    image.onerror =
      localizedDirectory === englishDirectory
        ? null
        : () => {
            image.onerror = null;
            image.src = fallbackSource;
          };
    image.src = `${localizedDirectory}/${fileName}`;
  });
}

function applyLanguage(language, updateUrl = false) {
  const activeLanguage = supportedLanguages.includes(language) ? language : "en";
  const copy = translations[activeLanguage];

  document.documentElement.lang = activeLanguage;
  document.title = copy.metaTitle;
  updateMeta("description", copy.metaDescription);
  updateMeta("og:title", copy.ogTitle, true);
  updateMeta("og:description", copy.ogDescription, true);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (value) element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const value = copy[element.dataset.i18nHtml];
    if (value) element.innerHTML = value;
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = copy[element.dataset.i18nAlt];
    if (value) element.setAttribute("alt", value);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const value = copy[element.dataset.i18nAria];
    if (value) element.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === activeLanguage));
  });

  updateScreenshots(activeLanguage);

  window.localStorage.setItem("playondlna-language", activeLanguage);

  if (updateUrl) {
    const url = new URL(window.location.href);
    if (activeLanguage === "en") {
      url.searchParams.delete("lang");
    } else {
      url.searchParams.set("lang", activeLanguage);
    }
    window.history.replaceState({}, "", `${url.pathname}${url.search}${url.hash}`);
  }
}

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.lang, true));
});

applyLanguage(preferredLanguage());
